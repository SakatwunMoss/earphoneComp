export function getColumnBySlug(slug: string): Column | undefined {
  return columns.find((column) => column.slug === slug);
}

export function formatColumnDate(publishedAt: string): string {
  const [year, month, day] = publishedAt.split("-").map(Number);
  if (!year || !month || !day) {
    return publishedAt;
  }
  return `${year}年${month}月${day}日`;
}
